-- ex02 윈도우 프레임 ROWS · RANGE (PDF E-33)  | SQL Server (RANGE 는 UNBOUNDED / CURRENT ROW 만 가능)
PRINT N'== [Q1] 기본 프레임(RANGE)';
SELECT empno, ename, sal, SUM(sal) OVER (ORDER BY sal) AS total_sal
FROM emp WHERE empno IN (7369, 7900, 7876, 7521, 7654, 7934) ORDER BY sal, empno;
PRINT N'== [Q2] ROWS 전체';
SELECT empno, ename, sal, SUM(sal) OVER (ORDER BY sal ROWS BETWEEN UNBOUNDED PRECEDING AND UNBOUNDED FOLLOWING) AS total_sal
FROM emp WHERE empno IN (7369, 7900, 7876, 7521, 7654, 7934) ORDER BY sal, empno;
PRINT N'== [Q3] ROWS UNBOUNDED PRECEDING AND 1 FOLLOWING';
SELECT empno, ename, sal, SUM(sal) OVER (ORDER BY sal, empno ROWS BETWEEN UNBOUNDED PRECEDING AND 1 FOLLOWING) AS total_sal
FROM emp WHERE empno IN (7369, 7900, 7876, 7521, 7654, 7934) ORDER BY sal, empno;
PRINT N'== [Q4] ROWS 누적';
SELECT empno, ename, sal, SUM(sal) OVER (ORDER BY sal, empno ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW) AS total_sal
FROM emp WHERE empno IN (7369, 7900, 7876, 7521, 7654, 7934) ORDER BY sal, empno;
PRINT N'== [Q5a] ROWS 1 PRECEDING ~ 1 FOLLOWING';
SELECT empno, ename, sal, SUM(sal) OVER (ORDER BY sal, empno ROWS BETWEEN 1 PRECEDING AND 1 FOLLOWING) AS rows_pm1
FROM emp WHERE empno IN (7369, 7900, 7876, 7521, 7654, 7934) ORDER BY sal, empno;
