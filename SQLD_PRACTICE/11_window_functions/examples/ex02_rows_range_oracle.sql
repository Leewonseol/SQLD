-- ex02 윈도우 프레임 ROWS · RANGE (PDF E-33)  | Oracle   데이터: EMP 중 PDF 와 같은 6명 (7369 800, 7900 950, 7876 1100, 7521 1250, 7654 1250, 7934 1300)
-- 동점(WARD·MARTIN 1250)의 상대 순서를 고정하려고 ROWS 프레임에서는 empno 를 2차 정렬 키로 둔다.
PROMPT == [Q1] PDF RANGE(기본 프레임): ORDER BY sal 만 쓰면 RANGE UNBOUNDED PRECEDING AND CURRENT ROW -> 같은 값은 함께 더한다
SELECT empno, ename, sal, SUM(sal) OVER (ORDER BY sal) AS total_sal
FROM emp WHERE empno IN (7369, 7900, 7876, 7521, 7654, 7934) ORDER BY sal, empno;

PROMPT == [Q2] PDF ROWS UNBOUNDED PRECEDING AND UNBOUNDED FOLLOWING: 모든 행이 전체 합 6650
SELECT empno, ename, sal, SUM(sal) OVER (ORDER BY sal ROWS BETWEEN UNBOUNDED PRECEDING AND UNBOUNDED FOLLOWING) AS total_sal
FROM emp WHERE empno IN (7369, 7900, 7876, 7521, 7654, 7934) ORDER BY sal, empno;

PROMPT == [Q3] PDF ROWS UNBOUNDED PRECEDING AND 1 FOLLOWING: 첫 행부터 다음 행까지
SELECT empno, ename, sal, SUM(sal) OVER (ORDER BY sal, empno ROWS BETWEEN UNBOUNDED PRECEDING AND 1 FOLLOWING) AS total_sal
FROM emp WHERE empno IN (7369, 7900, 7876, 7521, 7654, 7934) ORDER BY sal, empno;

PROMPT == [Q4] PDF ROWS UNBOUNDED PRECEDING AND CURRENT ROW: 행 단위 누적 (동점도 한 행씩)
SELECT empno, ename, sal, SUM(sal) OVER (ORDER BY sal, empno ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW) AS total_sal
FROM emp WHERE empno IN (7369, 7900, 7876, 7521, 7654, 7934) ORDER BY sal, empno;

PROMPT == [Q5] 이동 범위: ROWS 1 PRECEDING ~ 1 FOLLOWING (앞뒤 한 행) / RANGE 150 PRECEDING ~ CURRENT ROW (값 기준 150 이내)
SELECT empno, ename, sal,
       SUM(sal) OVER (ORDER BY sal, empno ROWS BETWEEN 1 PRECEDING AND 1 FOLLOWING) AS rows_pm1,
       SUM(sal) OVER (ORDER BY sal RANGE BETWEEN 150 PRECEDING AND CURRENT ROW) AS range_150
FROM emp WHERE empno IN (7369, 7900, 7876, 7521, 7654, 7934) ORDER BY sal, empno;

PROMPT == [Q6] 프레임 없이 ORDER BY 만 있으면 RANGE 기본 = Q1, ORDER BY 도 없으면 파티션 전체
SELECT ename, sal, SUM(sal) OVER () AS no_order FROM emp WHERE empno IN (7369, 7900) ORDER BY sal;
