-- ex03 날짜 함수와 날짜 연산  | SQL Server (고정 날짜)
PRINT N'== [Q1] DATEADD (DATE 형에 + 1 은 오류: Q7)';
SELECT DATEADD(DAY, 1, CAST('2024-01-31' AS DATE)) plus1, FORMAT(DATEADD(HOUR, 1, CAST('2024-01-31' AS DATETIME2(0))), 'yyyy-MM-dd HH:mm') plus1h;
PRINT N'== [Q2] DATEDIFF(DAY, 시작, 끝)';
SELECT DATEDIFF(DAY, '2024-02-01', '2024-03-01') days_feb_2024, DATEDIFF(DAY, '2023-02-01', '2023-03-01') days_feb_2023;
PRINT N'== [Q3] DATEADD(MONTH) 와 DATEDIFF(MONTH): DATEDIFF 는 "경계를 넘은 횟수"';
SELECT DATEADD(MONTH, 1, CAST('2024-01-31' AS DATE)) am1, DATEADD(MONTH, 12, CAST('2024-02-29' AS DATE)) am12,
       DATEDIFF(MONTH, '2024-02-29', '2024-03-31') dd_lastdays, DATEDIFF(MONTH, '2024-01-31', '2024-02-01') dd_1day;
PRINT N'== [Q4] EOMONTH / DATETRUNC(2022+) / 월초 계산';
SELECT EOMONTH('2024-02-10') last_d, DATETRUNC(MONTH, CAST('2024-03-15' AS DATE)) trunc_mm, DATETRUNC(YEAR, CAST('2024-03-15' AS DATE)) trunc_yy,
       DATEFROMPARTS(2024, 3, 1) first_day;
PRINT N'== [Q5] YEAR / MONTH / DATEPART / DAY';
SELECT YEAR('2024-03-15') y, MONTH('2024-03-15') m, DATEPART(DAY, '2024-03-15') dd;
PRINT N'== [Q6] 현재 시각: GETDATE(DATETIME), SYSDATETIME(DATETIME2)';
SELECT CASE WHEN GETDATE() > '2020-01-01' THEN 'GETDATE_OK' END chk;
PRINT N'== [Q8] DATETIME 형은 + 1 이 하루 덧셈으로 허용된다';
SELECT CAST('2024-01-31' AS DATETIME) + 1 dt_plus1;
